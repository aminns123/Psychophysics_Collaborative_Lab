"""Non-destructive, exploratory quick-look plots from canonical PsyCoLab trial data.

Both human and synthetic acquisitions can be inspected. Figures are DERIVED
artifacts beneath the external data root, never acquisition evidence or edits
to the original canonical trial records.
"""
from __future__ import annotations

import csv
from dataclasses import dataclass
from datetime import datetime, timezone
import hashlib
import json
import math
from pathlib import Path

from .thresholds import _owned_run, _read_manifest
from ..data.session import atomic_write_json


@dataclass(frozen=True)
class StaircasePreview:
    output_directory: Path
    plot_file: Path | None
    summary_file: Path


def latest_staircase_plot(*, data_root: Path, run_directory: Path) -> Path | None:
    run = _owned_run(Path(data_root), Path(run_directory))
    image = run / "analysis" / "staircases.png"
    if image.is_file() and not image.is_symlink():
        return image
    # Read-only migration for plots generated by earlier PsyCoLab versions.
    manifest = _read_manifest(run)
    uid = str(manifest.get("run_uuid", ""))
    if not uid or any(token in uid for token in ("/", "\\", "..")):
        return None
    legacy = Path(data_root).resolve() / "analysis" / "quicklook" / uid
    return next((p for p in sorted(legacy.glob("*/staircases.png"), reverse=True)
                 if p.is_file() and not p.is_symlink()), None)


def latest_threshold_plot(*, data_root: Path, run_directory: Path) -> Path | None:
    run = _owned_run(Path(data_root), Path(run_directory))
    image = run / "analysis" / "threshold_vs_condition.png"
    if image.is_file() and not image.is_symlink():
        return image
    # Read-only migration for historical, externally indexed analyses.
    manifest = _read_manifest(run)
    from .thresholds import _safe_component
    legacy = (Path(data_root).resolve() / "analysis" / "thresholds"
              / _safe_component(manifest.get("participant_id"))
              / _safe_component(manifest.get("experiment_id"))
              / _safe_component(manifest.get("run_uuid")))
    return next((p for p in sorted(legacy.glob("*/threshold_vs_condition.png"), reverse=True)
                 if p.is_file() and not p.is_symlink()), None)


def _sort_condition(key: str):
    try:
        return (0, float(key))
    except ValueError:
        return (1, key)


def create_staircase_preview(*, data_root: Path, run_directory: Path) -> StaircasePreview:
    """Plot independent per-condition staircases from accepted-response records.

    Separate panels are created only for conditions actually observed.
    Correct/incorrect response dots and reversal crosses are mapped from the
    canonical log, not synthesized from terminal staircase metadata.
    """
    data = Path(data_root).resolve()
    run = _owned_run(data, Path(run_directory))
    manifest = _read_manifest(run)
    if manifest.get("status") in {"configuring", "configured", "running"}:
        raise ValueError("Wait for canonical acquisition to finish before previewing it.")
    source = run / "trials.tsv"
    with source.open("r", newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream, delimiter="\t")
        if not reader.fieldnames:
            raise ValueError("No canonical trial header to preview.")
        required = {"staircase_id", "stimulus_condition", "presented_display_contrast",
                    "reversal", "correct"}
        if required - set(reader.fieldnames):
            raise ValueError("Staircase preview requires staircase ID, condition, response correctness and contrast.")
        rows = list(reader)
    by_condition: dict[str, dict[str, list[tuple[int, float, bool, bool]]]] = {}
    for row in rows:
        raw = str(row.get("presented_display_contrast", "")).strip()
        if not raw:
            continue
        contrast = float(raw)
        if not math.isfinite(contrast) or contrast < 0:
            raise ValueError("Nonfinite or negative presented contrast in canonical trials.")
        try:
            trial_index = int(row.get("staircase_trial_index") or row.get("trial_index"))
        except (ValueError, TypeError) as exc:
            raise ValueError("Each plotted response must have a positive accepted trial index.") from exc
        condition = str(row["stimulus_condition"])
        identity = str(row["staircase_id"])
        correct = str(row["correct"]).strip().lower() in {"1", "true"}
        reversal = str(row.get("reversal", "")).strip().lower() in {"1", "true"}
        by_condition.setdefault(condition, {}).setdefault(identity, []).append(
            (trial_index, contrast, correct, reversal)
        )

    output = run / "analysis"
    output.mkdir(exist_ok=True)
    png = None
    counts = {condition: len(staircases) for condition, staircases in by_condition.items()}
    if by_condition:
        import matplotlib
        matplotlib.use("Agg", force=True)
        import matplotlib.pyplot as plt
        from matplotlib.lines import Line2D

        ordered = sorted(by_condition, key=_sort_condition)
        columns = min(2, len(ordered))
        rows_count = math.ceil(len(ordered) / columns)
        fig, axes = plt.subplots(rows_count, columns, squeeze=False,
                                 figsize=(7.1 * columns, 4.3 * rows_count))
        for panel_index, condition in enumerate(ordered):
            ax = axes.flat[panel_index]
            staircases = by_condition[condition]
            values_all = [value[1] for values in staircases.values() for value in values]
            log_scale = bool(values_all) and all(value > 0 for value in values_all)
            for identity, values in sorted(staircases.items(), key=lambda item: _sort_condition(item[0])):
                sorted_values = sorted(values, key=lambda item: item[0])
                xx = [item[0] for item in sorted_values]
                yy = [item[1] for item in sorted_values]
                (line,) = ax.plot(xx, yy, marker=".", linewidth=1.15,
                                  label=f"Staircase {identity} ({len(values)} responses)")
                for target_correct, marker in ((True, "o"), (False, "x")):
                    chosen = [(x, y) for x, y, correct, _ in sorted_values if correct is target_correct]
                    if chosen:
                        ax.scatter([x for x, _ in chosen], [y for _, y in chosen],
                                   marker=marker, color=line.get_color(),
                                   s=24 if target_correct else 34, zorder=3)
                turns = [(x, y) for x, y, _, reversal in sorted_values if reversal]
                if turns:
                    ax.scatter([x for x, _ in turns], [y for _, y in turns],
                               marker="D", s=58, facecolors="none", edgecolors=line.get_color(),
                               linewidths=1.7, zorder=4)
            if log_scale:
                ax.set_yscale("log")
            ax.set_title(f"Condition {condition}  |  {len(staircases)} staircases  |  "
                         f"{sum(len(v) for v in staircases.values())} accepted responses")
            ax.set_xlabel("Accepted response number within staircase")
            ax.set_ylabel("Presented display contrast (normalised)")
            ax.grid(True, which="major", alpha=.22)
            ax.legend(fontsize=8, loc="best")
        for ax in axes.flat[len(ordered):]:
            ax.set_visible(False)
        legend = [
            Line2D([], [], color="black", marker="o", linestyle="none", label="Correct"),
            Line2D([], [], color="black", marker="x", linestyle="none", label="Incorrect"),
            Line2D([], [], color="black", marker="D", fillstyle="none", linestyle="none",
                   label="Reversal"),
        ]
        fig.legend(handles=legend, loc="upper center", ncol=3, fontsize=9)
        kind = manifest.get("data_kind", "human")
        fig.suptitle(f"Run staircases — {kind} — exploratory, not final thresholds", y=.997)
        fig.tight_layout(rect=(0, 0, 1, .95))
        png = output / "staircases.png"
        fig.savefig(png, dpi=145)
        plt.close(fig)

    summary = output / "staircase_preview.json"
    atomic_write_json(summary, {
        "schema_version": 2,
        "analysis": "nonfinal_staircase_quicklook",
        "source_run_relative": run.relative_to(data).as_posix(),
        "source_run_uuid": manifest.get("run_uuid"),
        "data_kind": manifest.get("data_kind", "human"),
        "canonical_trials_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "plotted_accepted_trials": sum(len(values) for group in by_condition.values() for values in group.values()),
        "condition_staircase_counts": counts,
        "staircases_plotted": sum(counts.values()),
        "plot": "staircases.png" if png else None,
        "warning": "Exploratory software output, not a final threshold or measured display timing.",
    })
    return StaircasePreview(output, png, summary)
